package io.karandash.testfixtures

import kotlinx.io.files.Path
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

class GoldenFilesTest {
    private val root = TestFiles.createTestTempDirectory("golden-files")

    @AfterTest
    fun cleanup() = TestFiles.deleteRecursively(root)

    @Test
    fun `a matching golden passes and trailing whitespace is normalized`() {
        TestFiles.writeText(Path(root, "a.txt"), "one\ntwo\n")

        assertNull(GoldenFiles.check(root, "a.txt", "one\ntwo  \n\n\n", update = false))
    }

    @Test
    fun `a missing golden is reported`() {
        val mismatch = GoldenFiles.check(root, "missing.txt", "x", update = false)

        assertTrue(mismatch.orEmpty().startsWith("missing golden"), "got $mismatch")
    }

    @Test
    fun `a differing golden reports the first differing line`() {
        TestFiles.writeText(Path(root, "b.txt"), "same\nold\ntail\n")

        val mismatch = GoldenFiles.check(root, "b.txt", "same\nnew\ntail", update = false).orEmpty()

        assertTrue(mismatch.contains("differs at line 2"), mismatch)
        assertTrue(mismatch.contains("expected <old> actual <new>"), mismatch)
    }

    @Test
    fun `a golden shorter than the output reports the first extra line`() {
        TestFiles.writeText(Path(root, "c.txt"), "a\n")

        val mismatch = GoldenFiles.check(root, "c.txt", "a\nb", update = false).orEmpty()

        assertTrue(mismatch.contains("differs at line 2"), mismatch)
    }

    @Test
    fun `update mode writes the golden into nested directories and passes`() {
        assertNull(GoldenFiles.check(root, "nested/dir/d.txt", "fresh\n\n", update = true))

        assertEquals("fresh\n", TestFiles.readText(Path(root, "nested/dir/d.txt")))
        assertNull(GoldenFiles.check(root, "nested/dir/d.txt", "fresh", update = false))
    }

    @Test
    fun `assertAllMatch passes on no mismatches and lists every mismatch with the regenerate hint`() {
        GoldenFiles.assertAllMatch(emptyList())

        val error = assertFailsWith<AssertionError> { GoldenFiles.assertAllMatch(listOf("first", "second")) }

        val message = error.message.orEmpty()
        assertTrue(message.contains("first\nsecond"), message)
        assertTrue(message.contains("-Dkarandash.updateGolden=true"), message)
    }

    @Test
    fun `assertMatches fails on a differing golden`() {
        TestFiles.writeText(Path(root, "e.txt"), "expected\n")

        GoldenFiles.assertMatches(root, "e.txt", "expected", update = false)
        assertFailsWith<AssertionError> { GoldenFiles.assertMatches(root, "e.txt", "other", update = false) }
    }

    @Test
    fun `normalize masks ansi codes timestamps durations and the repo root`() {
        val text = "\u001B[31mred\u001B[0m at 2026-10-23T10:15:30.123Z took 12ms or 1.5 s " +
            "\"durationMs\": 42 time=\"0.37\" Generated by karandash at 1761214530 in /repo/root/cli"

        val normalized = GoldenFiles.normalize(text, repoRoot = "/repo/root")

        assertEquals(
            "red at <ts> took <dur> or <dur> \"durationMs\": 0 time=\"0\" Generated by karandash at <ts> in <root>/cli",
            normalized,
        )
    }
}
