import java.io.File

plugins {
    id("karandash.kmp-library")
    id("karandash.publishing")
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.binary.compatibility.validator)
    alias(libs.plugins.dokka)
    alias(libs.plugins.atomicfu)
}

// Disable automatic dependency injection by the atomicfu plugin - matches the pattern
// used by plugins/plugins-ai/ai-core/build.gradle.kts to avoid duplicate deps on native
// test source sets.
atomicfu {
    dependenciesVersion = null
}

kotlin {
    explicitApi()

    sourceSets {
        commonMain.dependencies {
            api(project(":core:common"))
            api(project(":core:logger"))
            api(project(":core:models"))
            api(project(":core:normalize"))
            api(libs.kotlinx.serialization.json)
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlinx.atomicfu)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
    }
}

val generateVersionFile by tasks.registering {
    val outputDir = file("src/commonMain/kotlin/io/karandash")
    val versionFile = File(outputDir, "Version.kt")
    outputs.file(versionFile)
    inputs.property("version", project.version.toString())

    doLast {
        outputDir.mkdirs()
        versionFile.writeText(
            """
// AUTO-GENERATED by :core:api:generateVersionFile - DO NOT EDIT.
// Source of truth: `version` in the root build.gradle.kts `allprojects {}` block.
package io.karandash

public object Version {
    public const val NAME: String = "karandash"
    public const val VERSION: String = "${project.version}"
}
            """.trimIndent() + "\n"
        )
    }
}

tasks.named("compileKotlinJvm") { dependsOn(generateVersionFile) }

tasks
    .matching {
        it.name.startsWith("runKtlintCheck") ||
            it.name.startsWith("runKtlintFormat") ||
            it.name == "detekt"
    }.configureEach {
        mustRunAfter(generateVersionFile)
    }

// Ensure all Kotlin compile and sources-jar tasks depend on generateVersionFile (including BCV-triggered targets)
tasks.configureEach {
    if (name.startsWith("compileKotlin") ||
        (name.contains("compile") && name.contains("Metadata")) ||
        name.endsWith("SourcesJar", ignoreCase = true)
    ) {
        dependsOn(generateVersionFile)
    }
}
