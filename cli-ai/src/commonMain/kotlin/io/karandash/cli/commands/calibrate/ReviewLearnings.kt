package io.karandash.cli.commands.calibrate

import io.karandash.cli.commands.stats.audit.ClusterLabel
import io.karandash.cli.commands.stats.audit.ClusterMatcher
import io.karandash.cli.commands.stats.audit.ClusterOutcome
import io.karandash.cli.commands.stats.audit.MrAudit
import io.karandash.plugins.ai.core.Learning
import io.karandash.plugins.ai.core.LearningAction
import io.karandash.plugins.ai.core.LearningEvidence
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonPrimitive

/**
 * `calibrate --learn`: the `ai.learnings.file` entries an audit corpus supports. A rule (else, failing that, a rule
 * within one directory, counted over its whole subtree) gets an entry once reviewers rejected at least `minRejections` of its findings and at least
 * [MIN_REJECTED_SHARE] of the labelled ones: suppress when none was accepted, else downgrade.
 */
object ReviewLearnings {
    const val MIN_REJECTED_SHARE = 0.8

    fun learn(
        mrs: List<MrAudit>,
        minRejections: Int,
    ): List<Learning> =
        mrs
            .flatMap { it.clusters }
            .filter { it.rule != ClusterMatcher.UNKNOWN_RULE }
            .filter { it.label == ClusterLabel.ACCEPTED || it.label == ClusterLabel.REJECTED }
            .groupBy { it.rule }
            .toList()
            .sortedBy { it.first }
            .flatMap { (rule, clusters) ->
                entry(rule, null, clusters, minRejections)?.let { return@flatMap listOf(it) }
                clusters
                    .filter { '/' in it.path }
                    .map { it.path.substringBeforeLast('/') }
                    .distinct()
                    .sorted()
                    .mapNotNull { dir ->
                        // every cluster in the subtree, as the dir/** glob also matches findings in nested directories
                        entry(rule, "$dir/**", clusters.filter { it.path.startsWith("$dir/") }, minRejections)
                    }
            }

    private fun entry(
        rule: String,
        path: String?,
        clusters: List<ClusterOutcome>,
        minRejections: Int,
    ): Learning? {
        val rejected = clusters.count { it.label == ClusterLabel.REJECTED }
        if (rejected < minRejections || rejected < clusters.size * MIN_REJECTED_SHARE) return null
        val accepted = clusters.size - rejected
        val action = if (accepted == 0) LearningAction.SUPPRESS else LearningAction.DOWNGRADE
        return Learning(rule, path, action, LearningEvidence(rejected = rejected, accepted = accepted))
    }

    /** What [merge] made of the previous file: the new text and how many entries were kept, added and removed. */
    @Serializable
    data class Merged(
        val yaml: String,
        val kept: Int,
        val added: Int,
        val removed: Int,
    )

    /**
     * [learnings] merged into the [existing] file text: its entries without an `evidence` block are hand-written and
     * kept verbatim (first, so they win ties), the rest were generated by an earlier run and are replaced by [learnings].
     */
    fun merge(
        existing: String?,
        learnings: List<Learning>,
    ): Merged {
        val blocks = existing?.let(::entryBlocks).orEmpty()
        val (generated, handWritten) = blocks.partition { field(it, "evidence") != null }
        val old = generated.map(::key).toSet()
        val new = learnings.map { it.rule to it.path }.toSet()
        return Merged(yaml(learnings, handWritten), handWritten.size, (new - old).size, (old - new).size)
    }

    /** The `learnings:` list items of [text], each with its continuation lines; a list item starts at a line `- `. */
    private fun entryBlocks(text: String): List<String> {
        val blocks = mutableListOf<MutableList<String>>()
        text
            .lines()
            .dropWhile { !it.startsWith("learnings:") }
            .drop(1)
            .filter { it.isNotBlank() && !it.trimStart().startsWith("#") }
            .forEach { line -> if (line.trimStart().startsWith("- ")) blocks += mutableListOf(line) else blocks.lastOrNull()?.add(line) }
        return blocks.map { it.joinToString("\n") }
    }

    private fun key(block: String): Pair<String, String?> = field(block, "rule").orEmpty() to field(block, "path")

    /** Value of the top-level `name:` key of an entry [block], unquoted; null when it has none. */
    private fun field(
        block: String,
        name: String,
    ): String? =
        block.lines().firstNotNullOfOrNull { line ->
            line
                .trim()
                .removePrefix("- ")
                .trim()
                .takeIf { it.startsWith("$name:") }
                ?.removePrefix("$name:")
                ?.trim()
                ?.trim('"')
        }

    /** [learnings] as the learnings file, after the [handWritten] entry texts; strings are JSON-quoted, which YAML reads as double-quoted scalars. */
    fun yaml(
        learnings: List<Learning>,
        handWritten: List<String> = emptyList(),
    ): String =
        buildString {
            append("# Written by karandash calibrate --learn from review feedback. Review it before merging:\n")
            append("# the AI review reads it from the target branch and drops (suppress) or lowers (downgrade) matching findings.\n")
            if (learnings.isEmpty() && handWritten.isEmpty()) append("learnings: []\n") else append("learnings:\n")
            handWritten.forEach { append(it).append('\n') }
            learnings.forEach { l ->
                append("  - rule: ${JsonPrimitive(l.rule)}\n")
                l.path?.let { append("    path: ${JsonPrimitive(it)}\n") }
                append("    action: ${l.action.name.lowercase()}\n")
                append("    evidence: {rejected: ${l.evidence.rejected}, accepted: ${l.evidence.accepted}}\n")
            }
        }
}
