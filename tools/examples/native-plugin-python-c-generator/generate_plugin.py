def compile_shared_library(c_path: str, lib_name: str) -> str:
    """Compile C source to shared library."""
    system = platform.system()
    if system == "Darwin":
        ext = "dylib"
        flags = ["-dynamiclib"]
    elif system == "Linux":
        ext = "so"
        flags = ["-shared", "-fPIC"]
    else:
        ext = "dll"
        flags = ["-shared"]

    output = f"lib{lib_name}.{ext}"
    cmd = ["cc", "-O2", "-std=c11"] + flags + ["-o", output, c_path]
    print(f"Compiling: {' '.join(cmd)}")
    subprocess.check_call(cmd)
    return output


