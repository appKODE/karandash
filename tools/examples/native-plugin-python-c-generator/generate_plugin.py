def _generate_validate_body(rules: dict) -> str:
    """Generate the C validation dispatch logic from Python rule definitions."""
    cases = []
    for rule_id, rule in rules.items():
        if rule["check"] == "min_length":
            field = rule["field"]
            threshold = rule["threshold"]
            severity = rule["severity"]
            cases.append(textwrap.dedent(f"""\
                if (strcmp(rule_id, "{rule_id}") == 0) {{
                    const char* key = "\\"{field}\\":";
                    const char* pos = strstr(mr_json, key);
                    if (pos) {{
                        const char* val_start = strchr(pos + strlen(key), '\\x22');
                        if (val_start) {{
                            val_start++;
                            const char* val_end = strchr(val_start, '\\x22');
                            if (val_end && (val_end - val_start) < {threshold}) {{
                                char msg[256];
                                snprintf(msg, sizeof(msg),
                                    "[{{\\\"rule\\\":\\\"{rule_id}\\\","
                                    "\\\"severity\\\":\\\"{severity}\\\","
                                    "\\\"message\\\":\\\"{field} too short (%ld chars, minimum {threshold})\\\","
                                    "\\\"location\\\":null}}]",
                                    (long)(val_end - val_start));
                                return strdup(msg);
                            }}
                        }}
                    }}
                    return strdup("[]");
                }}"""))
        elif rule["check"] == "non_empty_array":
            field = rule["field"]
            severity = rule["severity"]
            message = rule["message_template"]
            cases.append(textwrap.dedent(f"""\
                if (strcmp(rule_id, "{rule_id}") == 0) {{
                    const char* key = "\\"{field}\\":";
                    const char* pos = strstr(mr_json, key);
                    if (pos) {{
                        const char* arr = strchr(pos + strlen(key), '[');
                        if (arr) {{
                            arr++;
                            while (*arr == ' ' || *arr == '\\n' || *arr == '\\t') arr++;
                            if (*arr != ']') return strdup("[]");
                        }}
                    }}
                    return strdup(
                        "[{{\\\"rule\\\":\\\"{rule_id}\\\","
                        "\\\"severity\\\":\\\"{severity}\\\","
                        "\\\"message\\\":\\\"{message}\\\","
                        "\\\"location\\\":null}}]"
                    );
                }}"""))
    return "\n    ".join(cases)


def generate_rule_c_source(rules: dict) -> str:
    """Generate the complete C plugin source for a RULE module."""
    rules_json = json.dumps(list(rules.keys()))
    escaped_rules_json = rules_json.replace('"', '\\"')
    validate_body = _generate_validate_body(rules)

    return textwrap.dedent(f"""\
        /* AUTO-GENERATED by generate_plugin.py — do not edit manually */
        #define _POSIX_C_SOURCE 200809L /* strdup is POSIX; -std=c11 hides it otherwise */
        #include <stdlib.h>
        #include <string.h>
        #include <stdio.h>
        #include <stdint.h>

        int32_t karandash_abi_version(void) {{ return 1; }}

        const char* karandash_module_id(void) {{ return strdup("{MODULE_ID}-rule"); }}
        const char* karandash_module_name(void) {{ return strdup("{MODULE_NAME} (Rule)"); }}
        const char* karandash_module_version(void) {{ return strdup("{MODULE_VERSION}"); }}
        const char* karandash_module_type(void) {{ return strdup("RULE"); }}

        int32_t karandash_initialize(const char* ctx) {{ (void)ctx; return 1; }}
        void karandash_shutdown(void) {{}}

        const char* karandash_contributed_rules(void) {{
            return strdup("{escaped_rules_json}");
        }}

        const char* karandash_validate(
            const char* rule_id,
            const char* mr_json,
            const char* config_json
        ) {{
            (void)config_json;
            {validate_body}
            return strdup("[]");
        }}

        void karandash_free_string(const char* ptr) {{
            if (ptr) free((void*)ptr);
        }}
    """)


