plugins {
    id("karandash.kmp-ktor-library")
    alias(libs.plugins.kotlin.serialization)
}

// Toolchain versions written into `karandash plugin create` / `generate` scaffolds, so generated projects
// build with the same Kotlin, coroutines and Gradle versions as this host (the SDK version is Version.VERSION).
val generateScaffoldVersions by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated-src/scaffold-versions/commonMain/kotlin")
    val versions = mapOf(
        "KOTLIN" to libs.versions.kotlin.get(),
        "COROUTINES" to libs.versions.kotlinxCoroutines.get(),
        "GRADLE" to gradle.gradleVersion,
    )
    inputs.property("versions", versions)
    outputs.dir(outputDir)
    doLast {
        val constants = versions.entries.joinToString("\n") { (key, value) -> "    const val $key: String = \"$value\"" }
        outputDir.get().file("io/karandash/registry/ScaffoldVersions.kt").asFile.apply {
            parentFile.mkdirs()
            writeText(
                "// AUTO-GENERATED by :plugins:registry:generateScaffoldVersions — DO NOT EDIT.\n" +
                    "package io.karandash.registry\n\ninternal object ScaffoldVersions {\n$constants\n}\n",
            )
        }
    }
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateScaffoldVersions)
        }
        commonMain.dependencies {
            api(project(":core:api"))
            api(project(":plugins:sdk"))
            implementation(project(":core:platform"))
            implementation(project(":core:crypto"))
