package io.karandash.platforms.gerrit

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Gerrit change information
 * Represents a Gerrit change (equivalent to a merge request in other platforms)
 */
@Serializable
data class GerritChangeInfo(
    val id: String,
    val project: String,
    @SerialName("change_id")
    val changeId: String,
    val subject: String,
    val status: String,
    val owner: GerritAccountInfo,
    val branch: String,
    @SerialName("current_revision")
    val currentRevision: String? = null,
    val revisions: Map<String, GerritRevisionInfo>? = null,
    val labels: Map<String, GerritChangeLabelInfo>? = null,
    val messages: List<GerritChangeMessageInfo>? = null,
    @SerialName("work_in_progress")
    val workInProgress: Boolean = false,
    val mergeable: Boolean? = null
)

/**
 * Gerrit account information
 */
@Serializable
data class GerritAccountInfo(
    @SerialName("_account_id")
    val accountId: Long,
    val name: String? = null,
    val email: String? = null,
    val username: String? = null
)

/**
 * Gerrit revision information
 */
@Serializable
data class GerritRevisionInfo(
    @SerialName("_number")
    val number: Int,
    val ref: String,
    val uploader: GerritAccountInfo? = null,
    val commit: GerritRevisionCommit? = null
)

/**
 * Gerrit commit information
 */
@Serializable
data class GerritRevisionCommit(
    val commit: String? = null,
    val subject: String,
    val message: String,
    val author: GerritGitPersonInfo,
    val committer: GerritGitPersonInfo
)

/**
 * Gerrit git person information (author/committer)
 */
@Serializable
data class GerritGitPersonInfo(
    val name: String,
    val email: String,
    val date: String? = null
)

/**
 * Gerrit label information (e.g., Code-Review, Verified)
 */
@Serializable
data class GerritChangeLabelInfo(
    val approved: GerritAccountInfo? = null,
    val rejected: GerritAccountInfo? = null,
    val value: Int? = null,
    val all: List<GerritChangeApprovalInfo>? = null
)

/**
 * Gerrit approval information for change-level label votes
 */
@Serializable
data class GerritChangeApprovalInfo(
    val value: Int,
    @SerialName("_account_id")
    val accountId: Long,
    val name: String? = null,
    val email: String? = null
)

/**
 * Gerrit change message (comment/review message)
 */
@Serializable
data class GerritChangeMessageInfo(
    val id: String,
    val author: GerritAccountInfo? = null,
    val date: String? = null,
    val message: String,
    @SerialName("_revision_number")
    val revisionNumber: Int? = null
)

/**
 * Request body for posting a review
 */
@Serializable
data class GerritReviewInput(
    val message: String? = null,
    val labels: Map<String, Int>? = null,
    @SerialName("omit_duplicate_comments")
    val omitDuplicateComments: Boolean? = null,
    /** `autogenerated:` tags let Gerrit's "Only comments" filter hide bot messages. */
    val tag: String? = null,
    /** Who Gerrit emails about this review. */
    val notify: GerritNotify? = null,
)

/**
 * Response from posting a review
 */
@Serializable
data class GerritReviewResult(
    val labels: Map<String, Int>? = null,
    val reviewers: Map<String, GerritAddReviewerResult>? = null
)

/**
 * Result of adding a reviewer
 */
@Serializable
data class GerritAddReviewerResult(
    val reviewers: List<GerritAccountInfo>? = null,
    val error: String? = null
)

/**
 * Request body for setting hashtags
 */
@Serializable
data class GerritHashtagsInput(
    val add: List<String>? = null,
    val remove: List<String>? = null
)

/**
 * A published inline comment, as `GET /changes/{id}/comments` lists it per file
 */
@Serializable
data class GerritPublishedComment(
    val id: String,
    val message: String? = null,
    @SerialName("patch_set")
    val patchSet: Int? = null,
    /** Not in the per-file listing itself; [GerritClient.listInlineComments] fills it from the map key. */
    val path: String? = null,
    val line: Int? = null,
    @SerialName("in_reply_to")
    val inReplyTo: String? = null,
    val author: GerritAccountInfo? = null,
    /** Whether the comment still needs addressing; the thread's latest comment decides the thread's state. */
    val unresolved: Boolean? = null,
    /** `yyyy-MM-dd HH:mm:ss.SSSSSSSSS` UTC, which sorts as text. */
    val updated: String? = null,
)

/**
 * Inline comment for a specific file and line in a Gerrit review
 */
@Serializable
data class GerritInlineComment(
    val line: Int,
    val message: String,
    /** Set on a reply: the id of the comment it answers. */
    @SerialName("in_reply_to")
    val inReplyTo: String? = null,
    /** `false` on a reply resolves its thread; null leaves Gerrit's default. */
    val unresolved: Boolean? = null,
    /** A multi-line comment; Gerrit then anchors it on `range.end_line` and ignores [line]. */
    val range: GerritCommentRange? = null,
)

/** Gerrit `CommentRange`: lines 1-based, characters 0-based, start inclusive, end exclusive. */
@Serializable
data class GerritCommentRange(
    @SerialName("start_line")
    val startLine: Int,
    @SerialName("start_character")
    val startCharacter: Int,
    @SerialName("end_line")
    val endLine: Int,
    @SerialName("end_character")
    val endCharacter: Int,
)

/**
 * Request body for posting a review with inline comments
 */
@Serializable
data class GerritInlineReviewInput(
    val message: String? = null,
    val comments: Map<String, List<GerritInlineComment>>? = null,
    @SerialName("omit_duplicate_comments")
    val omitDuplicateComments: Boolean? = null,
    /** See [GerritReviewInput.tag]. */
    val tag: String? = null,
    /** See [GerritReviewInput.notify]. */
    val notify: GerritNotify? = null,
)

/**
 * Request body for updating a change's commit message (subject line)
 */
@Serializable
data class GerritCommitMessageInput(
    val message: String
)

/** Response of `GET /changes/{id}/message`. */
@Serializable
data class GerritCommitMessageInfo(
    val subject: String = "",
    @SerialName("full_message")
    val fullMessage: String,
)
