package io.karandash.plugins.formats

import io.karandash.helpers.reporter.ReportMediaKeys
import io.karandash.models.finding.Finding
import io.karandash.models.finding.Location
import io.karandash.models.finding.Severity
import io.karandash.testfixtures.createTestReport
import io.karandash.translations.russian.RussianTranslationModule
import kotlinx.coroutines.test.runTest
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/** No unused styles, readable timestamp and fix-hint language for html. */
class HtmlFormatReportTest {
    @BeforeTest
    fun registerRussianPack() {
        RussianTranslationModule.register()
    }

    private suspend fun html(config: JsonObject = JsonObject(emptyMap())) =
        HtmlFormatModule()
            .format(
                createTestReport(
                    findings = listOf(
                        Finding(
                            severity = Severity.ERROR,
                            message = "bad",
                            rule = "r",
                            suggestion = "rename it",
                            location = Location.FileRef("a.kt", 2)
                        )
                    )
                ),
                config
            ).body

    @Test
    fun `the stylesheet has no unused finding classes and the timestamp is ISO`() =
        runTest {
            val body = html(JsonObject(mapOf("style" to JsonPrimitive("verbose"))))
            assertFalse(".finding-title" in body, body)
            assertTrue(Regex("Timestamp: \\d{4}-\\d{2}-\\d{2}T").containsMatchIn(body), body)
        }

    @Test
    fun `fix hint label follows the language`() =
        runTest {
            assertTrue(
                "Как исправить" in html(JsonObject(mapOf("language" to JsonPrimitive("ru")))),
                html(JsonObject(mapOf("language" to JsonPrimitive("ru"))))
            )
        }

    @Test
    fun `the email subject and the verbose header follow the language`() =
        runTest {
            val ru = JsonObject(mapOf("language" to JsonPrimitive("ru")))
            val report = createTestReport(findings = listOf(Finding(severity = Severity.ERROR, message = "bad", rule = "r")))
            val subject = HtmlFormatModule().format(report, ru).metadata[ReportMediaKeys.SUBJECT].orEmpty()
            assertTrue(subject.startsWith("[karandash] НЕ ПРОЙДЕНО"), subject)
            val verbose = html(JsonObject(mapOf("language" to JsonPrimitive("ru"), "style" to JsonPrimitive("verbose"))))
            assertFalse("FAILED" in verbose, verbose)
            assertEquals(
                "[karandash] FAILED",
                HtmlFormatModule().format(report, JsonObject(emptyMap())).metadata[ReportMediaKeys.SUBJECT]?.substringBefore(" ·")
            )
        }

    @Test
    fun `the verbose layout renders its fixed texts in the report language and keeps English unchanged`() =
        runTest {
            val english = html(JsonObject(mapOf("style" to JsonPrimitive("verbose"))))
            val englishTexts = listOf(
                "<h1>Karandash MR Validation: ",
                "<p><strong>Summary:</strong></p>",
                "<p>Errors: 1 | Warnings: 0 | Info: 0</p>",
                "<p>Total Findings: 1</p>",
                "<h2>Validation Findings</h2>",
                "<th>Severity</th>",
                "<th>Rule</th>",
                "<th>Message</th>",
                "<th>Location</th>",
                "font-weight: bold;\">ERROR</td>",
                "<p>Generated by Karandash MR Validation Tool</p>",
                "<p>Timestamp: ",
            )
            englishTexts.forEach { assertTrue(it in english, it) }

            val russian = html(JsonObject(mapOf("style" to JsonPrimitive("verbose"), "language" to JsonPrimitive("ru"))))

            assertTrue("<p>Ошибки: 1 | Предупреждения: 0 | Инфо: 0</p>" in russian, russian)
            assertTrue("<th>Важность</th>" in russian && "ОШИБКА</td>" in russian, russian)
            englishTexts.forEach { assertFalse(it in russian, it) }
        }
}
