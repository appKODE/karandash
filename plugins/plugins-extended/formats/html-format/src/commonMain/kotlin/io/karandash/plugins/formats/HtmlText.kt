package io.karandash.plugins.formats

import io.karandash.models.finding.Severity
import io.karandash.models.finding.Translations

/**
 * The fixed texts of the `verbose` HTML layout in English; other languages (`report.language`) from a pack. `%1`..`%3`
 * are values. [ERROR], [WARNING] and [INFO] label a finding's severity.
 */
internal enum class HtmlText(
    val en: String,
) {
    TITLE("Karandash MR Validation: %1"),
    SUMMARY("Summary:"),
    COUNTS("Errors: %1 | Warnings: %2 | Info: %3"),
    TOTAL("Total Findings: %1"),
    ALL_PASSED("All validation checks passed!"),
    FINDINGS("Validation Findings"),
    SEVERITY("Severity"),
    RULE("Rule"),
    MESSAGE("Message"),
    LOCATION("Location"),
    GENERATED("Generated by Karandash MR Validation Tool"),
    TIMESTAMP("Timestamp: %1"),
    ERROR("ERROR"),
    WARNING("WARNING"),
    INFO("INFO"),
    ;

    /** This text in [language] (English when unset or without a pack), `%1`.. filled with [values]. */
    fun of(
        language: String?,
        vararg values: Any,
    ): String = values.foldIndexed(Translations.text(en, language)) { i, acc, v -> acc.replace("%${i + 1}", v.toString()) }

    companion object {
        /** The label of [severity] in [language]. */
        fun severity(
            severity: Severity,
            language: String?,
        ): String =
            when (severity) {
                Severity.ERROR -> ERROR
                Severity.WARNING -> WARNING
                Severity.INFO -> INFO
            }.of(language)
    }
}
