package io.karandash.plugins.formats

import io.karandash.models.finding.PluralRule
import io.karandash.models.finding.Translations

/**
 * The fixed texts of the `verbose` Slack layout in English; other languages (`report.language`) from a pack. `%1`..`%3`
 * are values; a counted text has three forms `one|few|many` with `%d` for the number (English keeps `findings`).
 */
internal enum class SlackLayoutText(
    val en: String,
) {
    TITLE("Karandash Validation: %1"),
    ALL_PASSED("All validation checks passed!"),
    COUNTS("*Errors:* %1 | *Warnings:* %2 | *Info:* %3"),
    GENERATED("Generated by karandash at %1"),
    MORE("... and %d more findings|... and %d more findings|... and %d more findings"),
    ;

    /** This text in [language] (English when unset or without a pack), `%1`.. filled with [values]. */
    fun of(
        language: String?,
        vararg values: Any,
    ): String = values.foldIndexed(Translations.text(en, language)) { i, acc, v -> acc.replace("%${i + 1}", v.toString()) }

    /** The form of [n] of this counted text in [language]. */
    fun count(
        language: String?,
        n: Int,
    ): String = (Translations.pack(language)?.pluralRule ?: PluralRule.ONE_OTHER).count(Translations.text(en, language), n)
}
