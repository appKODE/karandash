/**
 * The output language of one summary: [SummaryText] in `en` or a language with a translation pack. A region
 * tag reads as its base tag (`ru-RU` is `ru`); any other language renders in English.
 */
internal class SummaryLocale private constructor(
    /** The language tag, passed to the shared [FixHintText] labels and [io.karandash.models.finding.Mismatch.describe]. */
    val tag: String,
) {
    fun t(text: FixHintText): String = text.text(tag)

    fun t(text: SummaryText): String = Translations.text(text.en, tag)

    fun t(
        text: SummaryText,
        count: Int,
    ): String = t(text).replace("%d", count.toString())

    fun t(
        text: SummaryText,
        ruleId: String,
    ): String = t(text).replace("%s", ruleId)

    companion object {
        /** The default English locale. */
        val EN = SummaryLocale("en")

        /** The locale of [language] (a BCP-47 tag); English when it is `null` or has no strings table. */
        fun of(language: String?): SummaryLocale =
            SummaryLocale(
                language
                    .orEmpty()
                    .trim()
                    .lowercase()
                    .substringBefore('-')
                    .substringBefore('_'),
            )
    }
}
